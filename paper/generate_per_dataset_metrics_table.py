"""Render audited historical counts; --check detects drift without writing files."""

import argparse
import json
import math
from pathlib import Path
from statistics import NormalDist

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'results/injection_aware_mpnet_evaluation.json'
OUTPUT = ROOT / 'paper/tables/per_dataset_metrics.tex'


def proportion(successes, total):
    """Format a proportion with a nominal 95% Wilson interval; absent class is N/A."""
    if total == 0:
        return 'N/A'
    p = successes / total
    z = NormalDist().inv_cdf(0.975)
    denom = 1 + z * z / total
    centre = (p + z * z / (2 * total)) / denom
    half = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total**2)) / denom
    low, high = max(0.0, centre - half), min(1.0, centre + half)
    return rf'\shortstack{{{100*p:.1f}\% \\ {{[{100*low:.1f}, {100*high:.1f}]}}}}'


def metrics(record):
    counts = record['confusion_matrix']
    tp, tn, fp, fn = (counts[key] for key in ('tp', 'tn', 'fp', 'fn'))
    if any(type(n) is not int or n < 0 for n in (tp, tn, fp, fn)):
        raise ValueError('Confusion counts must be nonnegative integers')
    n = tp + tn + fp + fn
    if not n or type(record['samples']) is not int or record['samples'] != n:
        raise ValueError('Sample count must match the nonempty confusion matrix')
    values = ((tp + tn, n), (tp, tp + fn), (fp, fp + tn))
    for key, (successes, total) in zip(('accuracy', 'recall', 'fpr'), values):
        if total and not math.isclose(record[key], successes / total, abs_tol=1e-8):
            raise ValueError(f'{key} disagrees with confusion counts')
    return [str(n)] + [proportion(k, total) for k, total in values]


def render(data):
    if data['model'] != 'injection_aware_mpnet' or data['threshold'] != 0.764:
        raise ValueError('Historical table requires the documented model and threshold')
    if data['date'] != '2025-12-16 03:24:39':
        raise ValueError('Historical record date changed; review provenance')
    names = {
        'deepset_benign': 'deepset (benign)',
        'deepset_injections': 'deepset (injections)',
        'NotInject': 'Local synthetic triggers',
        'Overall': 'Stored pooled record',
    }
    if set(data['datasets']) != set(names):
        raise ValueError('Dataset scope changed; review table provenance before rendering')
    lines = [
        '% Generated by paper/generate_per_dataset_metrics_table.py; do not hand-edit.',
        r'\begin{table}[H]', r'\centering', r'\small',
        r'\caption{Historical pre-remediation counts, $\theta=0.764$. '
        r'Nominal 95\% Wilson intervals in brackets; not held-out performance.}',
        r'\label{tab:per-dataset-metrics}',
        r'\begin{tabular}{lrccc}', r'\toprule',
        r'\textbf{Record} & $n$ & \textbf{Accuracy} & \textbf{Recall} & \textbf{FPR} \\',
        r'\midrule',
    ]
    for key, name in names.items():
        if key == 'Overall':
            lines.append(r'\midrule')
        lines.append(' & '.join([name] + metrics(data['datasets'][key])) + r' \\[3pt]')
    lines += [
        r'\bottomrule', r'\end{tabular}', r'\par\smallskip',
        r'\begin{minipage}{\linewidth}\footnotesize',
        r'Source: \path{results/injection_aware_mpnet_evaluation.json}, '
        r'2025-12-16 03:24:39. The pooled record includes SaTML and LLMail samples '
        r'whose individual confusion counts are not saved in this file; it is '
        r'not the sum of the three rows above. The synthetic trigger set is not '
        r'official NotInject. Intervals do not account for leakage or duplicates.',
        r'\end{minipage}', r'\end{table}', '',
    ]
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render(json.loads(SOURCE.read_text()))
    if args.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit('Historical table is stale; regenerate and review it')
        print('PASS: historical table matches validated confusion counts')
    else:
        OUTPUT.write_text(expected)
        print(f'Saved: {OUTPUT}')


if __name__ == '__main__':
    main()
